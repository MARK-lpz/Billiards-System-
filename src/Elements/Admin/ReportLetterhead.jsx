import { HALL_NAME } from "../../utils/reportExcel";

/**
 * The top of every printed report (Sales, Audit Trail), the same as its Excel
 * copy (reportExcel.js): the logo on navy with the hall's name, the report's
 * title and period on the right, the sign's four colours as a stripe under them,
 * then the report's details (`details`: [[label, value]]).
 */
export default function ReportLetterhead({ title, subtitle = "", details = [] }) {
  return (
    <header className="doc-head">
      <div className="doc-banner">
        <span className="doc-logo-frame">
          <img className="doc-logo" src="/Logo.png" alt="" />
        </span>
        <div className="doc-hall-name">
          <div className="doc-hall">BREAK &amp; CHILL</div>
          <div className="doc-hall-sub">BILLIARD HALL</div>
        </div>
        <div className="doc-banner-title">
          <h2 className="doc-title">{title}</h2>
          {subtitle && <div className="doc-subtitle">{subtitle}</div>}
        </div>
      </div>
      <div className="doc-tubes" aria-hidden="true">
        <span></span>
        <span></span>
        <span></span>
        <span></span>
      </div>
      {details.length > 0 && (
        <dl className="doc-details">
          {details.map(([label, value]) => (
            <div key={label}>
              <dt>{label}</dt>
              <dd>{value}</dd>
            </div>
          ))}
        </dl>
      )}
    </header>
  );
}

/** The foot of a printed report; each printed page also gets the page number (pagePrintCss). */
export function ReportFooter({ title }) {
  return (
    <footer className="doc-foot">
      <span>
        {HALL_NAME} · {title}
      </span>
      <span>Generated by the Break &amp; Chill system</span>
    </footer>
  );
}
